#!/usr/bin/env python3
"""Emit build/fontdata.s for the packed KH font binaries, as
.incbin segments F16B04-F16B18 / F12B19-F12B29 that reference ranges
of font16.bin / font12.bin directly (ca65 .incbin start/length), so
no per-bank chunk files are created. Run by the Makefile after
pack_font.py."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.join(HERE, '..', 'build')

def emit(lines, data, step, first_bank, tag, fname):
    for i in range((len(data) + step - 1) // step):
        off = i * step
        length = min(step, len(data) - off)
        assert length in (step, 2624, 6144), length
        lines.append('        .segment "%sB%02d"' % (tag, first_bank + i))
        lines.append('        .incbin "%s", %d, %d' % (fname, off, length))

def main():
    f16 = open(os.path.join(BUILD, 'font16.bin'), 'rb').read()
    f12 = open(os.path.join(BUILD, 'font12.bin'), 'rb').read()
    assert len(f16) == 3666 * 32 and len(f12) == 3666 * 24
    lines = ['; generated by tools/split_font.py -- do not edit',
             '; KH-Dot-Dougenzaka (SIL OFL 1.1), packed by pack_font.py']
    emit(lines, f16, 8192, 4, 'F16', 'font16.bin')   # banks 4-18
    emit(lines, f12, 8184, 19, 'F12', 'font12.bin')  # banks 19-29
    open(os.path.join(BUILD, 'fontdata.s'), 'w').write('\n'.join(lines) + '\n')

if __name__ == '__main__':
    main()
